// ─────────────────────────────────────────────────────────────────────────────
// Event Data Model — Component 4
// "Event Intelligence & Context-Aware Feature Engineering"
//
// This module defines the shared TypeScript data contracts for scheduled
// business events. These types are consumed by both the backend API and the
// frontend dashboard.
//
// Design decisions:
//   - String-literal unions (not TS enums) for EventType, ExpectedLoad,
//     EventPriority, and EventStatus. String-literal unions serialise to
//     plain JSON strings, avoid the TS reverse-mapping overhead, and are
//     easier to validate with Zod in Part 1.3.
//   - All datetime fields use ISO 8601 strings so the contract is
//     JSON-serialisation safe. Backend and frontend may parse them into
//     Date objects internally, but the shared API contract never uses Date.
//   - System-managed fields (eventId, status, createdAt, updatedAt) are
//     excluded from input types so the frontend can never claim authority
//     over them.
//   - No cache keys, TTL, eviction, or Redis operations — those belong to
//     other components.
//   - No Express, React, MongoDB, or browser-specific API dependencies.
// ─────────────────────────────────────────────────────────────────────────────

// ── Enums (string-literal unions) ────────────────────────────────────────────

/**
 * The category of a scheduled business event.
 *
 * Used downstream by the Event Intelligence module to determine which
 * API endpoints are likely to be affected and what load patterns to expect.
 */
export type EventType =
  | "RESULT_RELEASE"
  | "REGISTRATION"
  | "FLASH_SALE"
  | "TICKET_RELEASE"
  | "PROMOTIONAL_CAMPAIGN"
  | "PAYMENT_DEADLINE"
  | "OTHER";

/** All valid EventType values, useful for iteration and validation. */
export const EVENT_TYPES: readonly EventType[] = [
  "RESULT_RELEASE",
  "REGISTRATION",
  "FLASH_SALE",
  "TICKET_RELEASE",
  "PROMOTIONAL_CAMPAIGN",
  "PAYMENT_DEADLINE",
  "OTHER",
] as const;

/**
 * The anticipated traffic load during the event window.
 *
 * This guides prewarm-window sizing and feature-engineering weight
 * calculations in later phases.
 */
export type ExpectedLoad =
  | "LOW"
  | "MEDIUM"
  | "HIGH"
  | "VERY_HIGH"
  | "UNKNOWN";

/** All valid ExpectedLoad values. */
export const EXPECTED_LOADS: readonly ExpectedLoad[] = [
  "LOW",
  "MEDIUM",
  "HIGH",
  "VERY_HIGH",
  "UNKNOWN",
] as const;

/**
 * Priority level for scheduling and resource-allocation decisions.
 *
 * Higher-priority events may receive earlier prewarm windows and more
 * aggressive cache-preparation strategies.
 */
export type EventPriority =
  | "LOW"
  | "MEDIUM"
  | "HIGH"
  | "CRITICAL";

/** All valid EventPriority values. */
export const EVENT_PRIORITIES: readonly EventPriority[] = [
  "LOW",
  "MEDIUM",
  "HIGH",
  "CRITICAL",
] as const;

/**
 * Lifecycle status of a scheduled event.
 *
 * Transitions are system-managed; the frontend may display but never
 * directly set the status through an input type.
 */
export type EventStatus =
  | "SCHEDULED"
  | "PROCESSING"
  | "COMPLETED"
  | "CANCELLED";

/** All valid EventStatus values. */
export const EVENT_STATUSES: readonly EventStatus[] = [
  "SCHEDULED",
  "PROCESSING",
  "COMPLETED",
  "CANCELLED",
] as const;

// ── Core Event Interface ─────────────────────────────────────────────────────

/**
 * A scheduled business event that may later trigger event-aware
 * processing in the research system.
 *
 * This is the canonical read-model returned by the API. It includes both
 * user-provided fields and system-managed metadata.
 */
export interface ScheduledEvent {
  /** Unique identifier, generated by the system (e.g. UUID or MongoDB ObjectId). */
  eventId: string;

  /** Human-readable name of the event. */
  eventName: string;

  /** Category of the event, used for intelligence classification. */
  eventType: EventType;

  /** Free-text description of the event. */
  description?: string;

  /**
   * Start of the event window.
   * ISO 8601 datetime string with timezone (e.g. "2026-11-01T08:00:00+05:30").
   */
  startTime: string;

  /**
   * End of the event window.
   * ISO 8601 datetime string with timezone (e.g. "2026-11-01T18:00:00+05:30").
   */
  endTime: string;

  /** Anticipated traffic load during the event. */
  expectedLoad?: ExpectedLoad;

  /** Scheduling priority for resource-allocation decisions. */
  priority?: EventPriority;

  /**
   * Minutes before `startTime` during which the system should begin
   * prewarm activities (e.g. cache population).
   * Must be a non-negative integer.
   */
  prewarmWindowMinutes: number;

  /**
   * Lifecycle status of the event.
   * Managed exclusively by the system — never set by client input.
   */
  status: EventStatus;

  /** ISO 8601 datetime when the event record was created. System-generated. */
  createdAt: string;

  /** ISO 8601 datetime when the event record was last updated. System-managed. */
  updatedAt: string;
}

// ── Operation-Specific Types ─────────────────────────────────────────────────

/**
 * Fields required to create a new scheduled event.
 *
 * Excludes system-managed fields: `eventId`, `status`, `createdAt`, `updatedAt`.
 */
export interface CreateScheduledEventInput {
  eventName: string;
  eventType: EventType;
  description?: string;
  /** ISO 8601 datetime string with timezone. */
  startTime: string;
  /** ISO 8601 datetime string with timezone. */
  endTime: string;
  expectedLoad?: ExpectedLoad;
  priority?: EventPriority;
  /** Non-negative integer — minutes before startTime to begin prewarm. */
  prewarmWindowMinutes: number;
}

/**
 * Fields that may be updated on an existing scheduled event.
 *
 * All user-editable fields are optional (partial update). System-managed
 * fields (`eventId`, `status`, `createdAt`, `updatedAt`) are intentionally
 * excluded so they can never be overwritten by client input.
 */
export type UpdateScheduledEventInput = Partial<CreateScheduledEventInput>;

// ── API Response Types ───────────────────────────────────────────────────────

/**
 * API response wrapper for a single event.
 *
 * Reuses `ScheduledEvent` rather than duplicating fields.
 */
export interface EventResponse {
  event: ScheduledEvent;
}

/**
 * Pagination metadata included in list responses.
 *
 * Defined now so the contract is stable; actual pagination logic will be
 * implemented when the Event Management API is built.
 */
export interface PaginationMeta {
  /** Total number of events matching the query. */
  total: number;
  /** Current page number (1-indexed). */
  page: number;
  /** Number of events per page. */
  limit: number;
  /** Total number of pages. */
  totalPages: number;
}

/**
 * API response wrapper for listing events with pagination metadata.
 */
export interface EventListResponse {
  events: ScheduledEvent[];
  pagination: PaginationMeta;
}

/**
 * Query filters and pagination parameters for listing scheduled events.
 */
export interface ListEventsQuery {
  /** Page number (1-indexed). Defaults to 1. */
  page?: number;
  /** Number of events per page. Defaults to 20, max 100. */
  limit?: number;
  /** Filter by event lifecycle status. */
  status?: EventStatus;
  /** Filter by event classification type. */
  eventType?: EventType;
  /** Filter by resource scheduling priority. */
  priority?: EventPriority;
  /** Filter by anticipated traffic load. */
  expectedLoad?: ExpectedLoad;
  /** Filter events starting on or after this ISO 8601 timestamp. */
  startDateFrom?: string;
  /** Filter events starting on or before this ISO 8601 timestamp. */
  startDateTo?: string;
  /** Field to sort by. Defaults to "startTime". */
  sortBy?: "startTime" | "createdAt" | "eventName";
  /** Sort order direction. Defaults to "asc". */
  sortOrder?: "asc" | "desc";
}
