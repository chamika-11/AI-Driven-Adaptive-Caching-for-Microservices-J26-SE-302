"""Generate the data-driven parts of the thesis write-up material (tables + figures) from the results files.

    python scripts/make_thesis_material.py      # -> docs/thesis/02_key_tables.md and docs/thesis/figures/*.png
"""
import shutil
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from rlcache.analysis.pareto import envelope  # noqa: E402

OUT = ROOT / "docs" / "thesis"
FIG = OUT / "figures"
FIG.mkdir(parents=True, exist_ok=True)

syn = pd.read_csv(ROOT / "results" / "results.csv")
r1 = pd.read_csv(ROOT / "results" / "real_cluster52.csv")
r2 = pd.read_csv(ROOT / "results" / "real_r2.csv")
TR = {"c52": "cluster52.000-002_k1", "c22": "cluster22.000_k2"}

# ---------------------------------------------------------------- helpers
def agg(df, trace=None, cap=0.01, split="test", arm=None):
    d = df[(df.split == split) & (df.capacity_frac == cap)]
    if trace is not None:
        d = d[d.trace_name == trace]
    if "staleness_mode" in d:
        d = d[d.staleness_mode == "harsh"]
    g = d.groupby("policy")
    out = pd.DataFrame({"U": g.utility.mean(), "U_sd": g.utility.std(), "OHR": 100 * g.ohr.mean(),
                        "stale": 100 * g.stale_read_rate.mean(), "n": g.seed.nunique(), "cls": g.policy_class.first()})
    return out


def md(df, cols, fmt):
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for idx, r in df.iterrows():
        cells = [str(idx)] + [fmt[c].format(r[c]) if c in fmt else str(r[c]) for c in cols[1:]]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


AG = ["dqn:main", "dqn:bandit", "dqn:vanilla", "tabq:qbin", "tabq:bandit", "dqn:main@s3fifo"]
REFS = ["random:45", "place_size:p25", "evict:s3fifo/redis/3600s", "evict:s3fifo/both/3600s", "evict:lru/both/3600s", "fixed:both/3600s/normal"]
fmt = {"U": "{:.4f}", "OHR": "{:.2f}", "stale": "{:.3f}"}


def block(title, a, extra=()):
    rows = [p for p in list(REFS) + list(AG) + list(extra) if p in a.index]
    best = a[(a.cls == "heuristic")].sort_values("U", ascending=False).head(1)
    sel = a.loc[rows]
    if len(best) and best.index[0] not in sel.index:
        sel = pd.concat([best, sel])
    sel = sel.sort_values("U", ascending=False)
    t = md(sel[["U", "OHR", "stale"]].reset_index().rename(columns={"index": "policy", "policy": "policy"}).set_index("policy"),
           ["policy", "U", "OHR", "stale"], fmt)
    return f"### {title}\n\n{t}\n"


parts = ["# Key tables (generated by `scripts/make_thesis_material.py`; numbers are means over seeds, test slice)\n",
         "U = the project's selection utility (hits + 0.5 x speed score - 3 x stale cost, per read); OHR = object hit ratio %; stale = stale-read rate %. "
         "All staleness/latency is MODELLED. Higher U and OHR, lower stale are better. Synthetic = made-up traffic (10 seeds); real = Twitter traces (5 seeds).\n"]
for cap in (0.01, 0.05, 0.25):
    a = agg(syn, cap=cap)
    parts.append(block(f"A{int(cap*100)}. SYNTHETIC traffic, L2 = {cap:.0%} of footprint (10 evaluation seeds)", a))
a = agg(r1, trace="cluster52.000_k1")
parts.append(block("B. REAL traffic, cluster 52 part 000 (2.2 h, 1% of keys), L2 = 1% (5 seeds; Addendum R1)", a))
a52 = agg(r2, trace=TR["c52"])
parts.append(block("C1. REAL traffic, cluster 52 parts 000-002 (5.7 h, 1% of keys), L2 = 1% (5 seeds; Addendum R2)", a52))
a22 = agg(r2, trace=TR["c22"])
parts.append(block("C2. REAL traffic, cluster 22 part 000 (10 h, 2% of keys), L2 = 1% (5 seeds; Addendum R2)", a22))

# cross-trace table
rows = []
for A, B in (("c52", "c22"), ("c22", "c52")):
    t = r2[(r2.trace_name == TR[B]) & (r2.split == "test") & (r2.capacity_frac == 0.01)]
    for ag in ("dqn:main", "dqn:bandit", "dqn:main@s3fifo"):
        own = t[t.policy == ag].utility.mean()
        xf = t[t.policy == f"{ag}@from_{A}"].utility.mean()
        ref = t[t.policy == "evict:s3fifo/redis/3600s"].utility.mean()
        rnd = t[t.policy == "random:45"].utility.mean()
        rows.append((f"{A} -> {B}", ag, own, xf, rnd, ref))
ct = pd.DataFrame(rows, columns=["train -> test", "agent", "U trained on test trace", "U trained on other trace", "U random", "U S3-FIFO rule"])
parts.append("### D. Cross-trace test (agent trained on one real cluster, tested on the other; 1%, 5 seeds)\n\n" +
             md(ct.set_index("train -> test").reset_index().set_index("train -> test"), ["train -> test", "agent", "U trained on test trace", "U trained on other trace", "U random", "U S3-FIFO rule"],
                {c: "{:.4f}" for c in ct.columns[2:]}) + "\n")
(OUT / "02_key_tables.md").write_text("\n".join(parts), encoding="utf-8")

# ---------------------------------------------------------------- figures
import matplotlib  # noqa: E402
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

COL = {"agent": "#d95f02", "rule": "#1b9e77", "other": "#7570b3"}


def kind(p):
    return "agent" if (p.startswith("dqn") or p.startswith("tabq")) else ("rule" if p.startswith("evict:") or p.startswith("fixed:") or p.startswith("place") else "other")


fig, axes = plt.subplots(1, 3, figsize=(15, 5.2))
panels = [("Synthetic traffic, 1% cache (10 seeds)", agg(syn, cap=0.01)), ("Real: cluster 52 (5.7 h), 1% cache (5 seeds)", a52),
          ("Real: cluster 22 (10 h), 1% cache (5 seeds)", a22)]
show = ["random:45", "place_size:p25", "evict:fifo/both/3600s", "evict:lru/both/3600s", "evict:sieve/redis/3600s", "evict:s3fifo/redis/3600s", "dqn:main", "dqn:bandit", "tabq:qbin"]
for ax, (title, a) in zip(axes, panels):
    ps = [p for p in show if p in a.index]
    ps = sorted(ps, key=lambda p: a.loc[p, "U"])
    ax.barh(range(len(ps)), [a.loc[p, "U"] for p in ps], xerr=[a.loc[p, "U_sd"] for p in ps], color=[COL[kind(p)] for p in ps], alpha=0.9, capsize=2)
    ax.set_yticks(range(len(ps))); ax.set_yticklabels(ps, fontsize=8)
    lo = min(a.loc[p, "U"] for p in ps) - 0.08
    ax.set_xlim(lo, max(a.loc[p, "U"] for p in ps) + 0.05)
    ax.set_title(title, fontsize=10); ax.set_xlabel("selection utility U (higher is better)")
fig.suptitle("Where the learning agents (orange) rank: simple rules (green) are ahead on every data set", fontsize=11)
fig.tight_layout(); fig.savefig(FIG / "fig1_ranking_all_datasets.png", dpi=140); plt.close(fig)

fig, axes = plt.subplots(1, 2, figsize=(12, 5))
for ax, (title, tkey, df) in zip(axes, [("Real: cluster 52 (5.7 h), 1% cache", "c52", r2), ("Real: cluster 22 (10 h), 1% cache", "c22", r2)]):
    a = agg(df, trace=TR[tkey])
    base = a[(a.cls == "heuristic") & (~a.index.str.startswith("dqn"))]
    ax.scatter(base.stale, base.OHR, s=14, c="#999999", label="baselines (non-learned)")
    env = envelope(base.stale.to_numpy() / 100, base.OHR.to_numpy() / 100)
    ax.plot(100 * env[:, 0], 100 * env[:, 1], "-", c="#1b9e77", lw=1.6, label="best-achievable envelope of the baselines")
    for ag, mk in (("dqn:main", "o"), ("dqn:bandit", "s"), ("dqn:main@s3fifo", "^")):
        if ag in a.index:
            ax.scatter([a.loc[ag, "stale"]], [a.loc[ag, "OHR"]], s=90, marker=mk, c=COL["agent"], edgecolor="k", label=ag, zorder=5)
    ax.set_xlabel("stale reads %  (lower is better)"); ax.set_ylabel("object hit ratio %  (higher is better)")
    ax.set_title(title, fontsize=10); ax.legend(fontsize=7, loc="lower right")
fig.suptitle("Hit ratio vs stale reads: an agent would have to sit up-and-left of the green line to dominate", fontsize=11)
fig.tight_layout(); fig.savefig(FIG / "fig2_hit_vs_stale_real.png", dpi=140); plt.close(fig)

fig, axes = plt.subplots(1, 2, figsize=(11, 4.4))
for ax, (A, B) in zip(axes, (("c52", "c22"), ("c22", "c52"))):
    t = r2[(r2.trace_name == TR[B]) & (r2.split == "test") & (r2.capacity_frac == 0.01)]
    arms = ["dqn:main", "dqn:bandit", "dqn:main@s3fifo"]
    own = [t[t.policy == a_].utility.mean() for a_ in arms]
    xf = [t[t.policy == f"{a_}@from_{A}"].utility.mean() for a_ in arms]
    x = np.arange(3)
    ax.bar(x - 0.2, own, 0.4, label=f"trained on {B} (same trace)", color="#d95f02")
    ax.bar(x + 0.2, xf, 0.4, label=f"trained on {A} (transferred)", color="#7570b3")
    ax.axhline(t[t.policy == "evict:s3fifo/redis/3600s"].utility.mean(), c="#1b9e77", ls="--", label="S3-FIFO rule")
    ax.axhline(t[t.policy == "random:45"].utility.mean(), c="k", ls=":", label="random")
    ax.set_xticks(x); ax.set_xticklabels(arms, fontsize=8)
    lo = min(own + xf + [t[t.policy == "random:45"].utility.mean()]) - 0.05
    ax.set_ylim(lo, max(own + xf + [t[t.policy == "evict:s3fifo/redis/3600s"].utility.mean()]) + 0.03)
    ax.set_title(f"tested on {B}", fontsize=10); ax.set_ylabel("U"); ax.legend(fontsize=7)
fig.suptitle("Cross-trace test: how much is lost when the agent is moved to a different real cluster", fontsize=11)
fig.tight_layout(); fig.savefig(FIG / "fig3_cross_trace.png", dpi=140); plt.close(fig)

